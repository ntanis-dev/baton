//! The sign-in screen: what to do on the left, and Claude Code's public sign-in link on the right. The
//! link is shown by a name, never by its text.

use baton_core::art::branding;
use baton_core::lines::{Line, fit_line, p, s, wrap_line};
use baton_core::text::width as cells;

use super::kit::{Float, ON_TERMINAL, block, on_surface, overlay, theme_of};
use super::splash::splash;
use crate::layout::{SIDEBAR_COLS, body_height, frame_cols, frame_rows, too_small};
use crate::state::State;
use crate::views::common::section_rule;

/// The cells of a frame that open a link.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LinkAt {
    /// The row.
    pub row: usize,
    /// The first column.
    pub col: usize,
    /// How many cells.
    pub width: usize,
    /// Where it leads.
    pub url: String,
}

/// The sign-in screen as rows.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LoginFrame {
    /// The rows: every row but the terminal's last one, each exactly as wide as the terminal.
    pub rows: Vec<Line>,
    /// The cells that open the sign-in link, for the terminal to make a hyperlink of.
    pub link: Option<LinkAt>,
}

/// The host of a URL, for showing where a link leads.
fn host_of(url: &str) -> &str {
    let rest = url.split_once("://").map_or(url, |(_, rest)| rest);
    let authority = rest.split(['/', '?', '#']).next().unwrap_or(rest);
    let host = authority.rsplit('@').next().unwrap_or(authority);
    host.split(':').next().unwrap_or(host)
}

/// The sign-in screen for the account called `name`: `url` is Claude Code's sign-in link once it gave
/// one, `code_prompt` whether it asks for a verification code. Only `size`, `color` and `glyphs` of the
/// state are looked at.
pub fn login_frame(state: &State, name: &str, url: Option<&str>, code_prompt: bool) -> LoginFrame {
    let theme = theme_of(state);
    let g = theme.g;
    let cols = frame_cols(state);
    let rows = frame_rows(state);
    if too_small(state) {
        return LoginFrame {
            rows: splash(state, true),
            link: None,
        };
    }
    let height = body_height(state);
    let width = cols.saturating_sub(SIDEBAR_COLS + 6);
    let mut rail: Vec<Line> = vec![Vec::new()];
    rail.extend(branding("  "));
    rail.extend([
        Vec::new(),
        Vec::new(),
        vec![s("  CONNECT ACCOUNT", "muted")],
        Vec::new(),
    ]);
    rail.extend(wrap_line(&[s(format!("  {name}"), "bold")], SIDEBAR_COLS - 4, 2));
    rail.extend([
        Vec::new(),
        Vec::new(),
        vec![s("  01 ", "accent bold"), s("Open your browser", "muted")],
        Vec::new(),
        vec![
            s("  02 ", if url.is_some() { "accent bold" } else { "muted" }),
            s("Sign in to Claude", if url.is_some() { "text" } else { "muted" }),
        ],
        Vec::new(),
        vec![s("  03 ", "muted"), s("Return to Baton", "muted")],
    ]);
    let mut body: Vec<Line> = vec![
        Vec::new(),
        vec![s("Connect account", "bold")],
        vec![s("A new connection. The same conversation.", "muted")],
        Vec::new(),
        Vec::new(),
        section_rule("BROWSER SIGN-IN", width, g),
        Vec::new(),
    ];
    let opening = if url.is_some() {
        "Continue in your browser."
    } else {
        "Opening Claude sign-in..."
    };
    body.extend(wrap_line(&[s(opening, "bold")], width, 0));
    body.push(Vec::new());
    body.extend(wrap_line(
        &[s(
            "Sign in to the Claude account you want to use with Baton.",
            "muted",
        )],
        width,
        0,
    ));
    body.extend([
        Vec::new(),
        Vec::new(),
        section_rule("YOUR SIGN-IN LINK", width, g),
        Vec::new(),
    ]);
    let link_row = body.len();
    let link_text = if url.is_some() {
        format!("Open Claude sign-in {}", g.right)
    } else {
        "Waiting for your secure link".to_owned()
    };
    body.extend(wrap_line(&[s(&link_text, "accent bold underline")], width, 0));
    body.push(vec![s(url.map_or("Generated by Claude Code", host_of), "muted")]);
    body.push(Vec::new());
    let hint = if url.is_some() {
        "Ctrl+click the link if your browser did not open."
    } else {
        "Your browser will open automatically."
    };
    body.extend(wrap_line(&[s(hint, "muted")], width, 0));
    let rule = s("\u{2502}", &format!("divider {ON_TERMINAL}"));
    let rail_rows = block(&rail, SIDEBAR_COLS - 3, Some(height));
    let body_rows = block(&body, width, Some(height));
    let mut out: Vec<Line> = rail_rows
        .into_iter()
        .zip(body_rows)
        .map(|(left, right)| {
            let mut side = vec![p(" ")];
            side.extend(left);
            side.push(p(" "));
            let mut row = on_surface(&side);
            row.push(rule.clone());
            row.push(p("   "));
            row.extend(right);
            fit_line(&row, cols, "")
        })
        .collect();
    out.extend(block(
        &[vec![s("  Ctrl+C", "accent bold"), s(" Cancel", "muted")]],
        cols,
        Some(1),
    ));
    if code_prompt {
        let prompt = [
            vec![s("VERIFICATION CODE", "muted")],
            vec![s("Paste your code, then press Enter.", "muted")],
            vec![s("> ", "accent bold")],
        ];
        // The prompt sits on the frame's own background, not on a surface.
        let float = Float {
            top: rows.saturating_sub(6),
            left: SIDEBAR_COLS + 3,
            width,
            surface: false,
        };
        overlay(&mut out, float, &prompt);
    }
    out.truncate(rows);
    let link = url.filter(|_| link_row < height).map(|url| LinkAt {
        row: link_row,
        col: SIDEBAR_COLS + 3,
        width: cells(&link_text).min(width),
        url: url.to_owned(),
    });
    LoginFrame { rows: out, link }
}
