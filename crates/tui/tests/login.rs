const URL: &str = "https://claude.ai/oauth/authorize?client_id=fixture&state=public&code=true";

#[test]
fn the_sign_in_layout_carries_the_ascii_identity_and_fits_the_supported_terminal_sizes() {
    for size in [
        Size { cols: 100, rows: 28 },
        Size { cols: 120, rows: 30 },
        Size { cols: 160, rows: 45 },
    ] {
        let state = initial_state(Init {
            size,
            color: false,
            ..Init::default()
        });
        let drawn = login_frame(&state, "work@example.com", Some(URL), true);
        let lines: Vec<String> = drawn.rows.iter().map(|row| plain(row)).collect();
        assert_eq!(lines.len(), size.rows - 1);
        assert!(lines.iter().all(|line| width(line) == size.cols));
        let text = lines.join("\n");
        for line in LOGO {
            assert!(text.contains(line.trim()));
        }
        assert!(text.contains("Connect account"));
        assert!(text.contains("Open Claude sign-in"));
        assert!(text.contains("VERIFICATION CODE"));
        assert!(!text.contains("client_id") && !text.contains("state=public"));
        // The link is given by its cells, for the terminal to make a hyperlink of.
        let link = drawn.link.unwrap();
        assert_eq!(link.url, URL);
        let shown: String = lines[link.row].chars().skip(link.col).take(link.width).collect();
        assert_eq!(shown, "Open Claude sign-in \u{2192}");
    }
}

#[test]
fn the_sign_in_screen_waits_for_the_link_and_gives_way_to_the_size_error() {
    let state = initial_state(Init {
        size: Size { cols: 120, rows: 30 },
        color: false,
        ..Init::default()
    });
    let waiting = login_frame(&state, "work@example.com", None, false);
    let text = waiting
        .rows
        .iter()
        .map(|row| plain(row))
        .collect::<Vec<_>>()
        .join("\n");
    assert!(waiting.link.is_none());
    assert!(text.contains("Waiting for your secure link"));
    assert!(text.contains("Opening Claude sign-in..."));
    assert!(text.contains("Generated by Claude Code"));
    assert!(!text.contains("VERIFICATION CODE"));
    assert!(text.contains("Ctrl+C Cancel"));
    let linked = login_frame(&state, "work@example.com", Some(URL), false);
    let text = linked
        .rows
        .iter()
        .map(|row| plain(row))
        .collect::<Vec<_>>()
        .join("\n");
    assert!(text.contains("claude.ai"));
    assert!(text.contains("Ctrl+click the link if your browser did not open."));
    let small = initial_state(Init {
        size: Size { cols: 80, rows: 24 },
        color: false,
        ..Init::default()
    });
    let error = login_frame(&small, "work@example.com", Some(URL), true);
    assert!(error.link.is_none());
    assert_eq!(error.rows.len(), 23);
    assert!(
        error
            .rows
            .iter()
            .map(|row| plain(row))
            .collect::<Vec<_>>()
            .join("\n")
            .contains("Baton needs 100 x 28")
    );
}

#[test]
fn every_frame_is_exactly_as_large_as_the_terminal_less_its_last_row() {
    let home = temp_home();
    build_home(&home.paths, false);
    for (_, size) in sizes() {
        for (name, keys) in screens() {
            let mut state = menu_state_with(&home.paths, size, &keys, GlyphSet::Rich);
            state = toast(&state, "Saved the thresholds of acct2.", Tone::Ok);
            state = toast(
                &state,
                "A second note, long enough to wrap in a narrow toast when it has to.",
                Tone::Error,
            );
            for tick in [0, 3] {
                let rows = frame(&state, tick);
                assert_eq!(rows.len(), size.rows - 1, "{name}");
                assert!(
                    rows.iter().all(|row| line_width(row) == size.cols),
                    "{name} at tick {tick}"
                );
            }
        }
    }
}

#[test]
fn the_spinner_turns_with_the_tick_and_nothing_else_moves() {
    let home = temp_home();
    build_home(&home.paths, false);
    let state = menu_state_with(&home.paths, Size { cols: 120, rows: 30 }, &[], GlyphSet::Rich);
    let first = frame_text(&state, 0);
    let later = frame_text(&state, 3);
    assert_ne!(first, later);
    assert!(first.join("\n").contains(RICH.spinner[0]));
    assert!(!later.join("\n").contains(RICH.spinner[0]));
    let back: Vec<String> = later
        .iter()
        .map(|row| row.replace(RICH.spinner[3], RICH.spinner[0]))
        .collect();
    assert_eq!(first, back);
    assert_eq!(frame_text(&state, 10), first, "ten frames to a turn");
    // No span of a frame still asks for a spinner.
    assert!(
        frame(&state, 0)
            .iter()
            .flatten()
            .all(|span| !span.style.split(' ').any(|word| word == "spin"))
    );
}

#[test]
fn the_frame_is_on_its_background_and_the_sidebar_and_floats_on_the_surface() {
    let home = temp_home();
    build_home(&home.paths, false);
    let mut state = menu_state_with(
        &home.paths,
        Size { cols: 120, rows: 30 },
        &["down", "down", "enter"],
        GlyphSet::Rich,
    );
    state.color = true;
    let theme = theme_of(&state);
    let rows = frame(&state, 0);
    // The background of the cell at a column of a row.
    let background = |row: usize, col: usize| {
        let mut at = 0;
        for span in &rows[row] {
            at += width(&span.text);
            if col < at {
                return props(&theme, &span.style).background;
            }
        }
        None
    };
    assert_eq!(background(1, 2).as_deref(), Some("#181b20"), "the sidebar");
    assert_eq!(background(1, 60).as_deref(), Some("#121519"), "the pane");
    assert_eq!(background(28, 2).as_deref(), Some("#121519"), "the footer");
    let dialog = rows
        .iter()
        .position(|row| plain(row).contains("Account actions"))
        .unwrap();
    let col = plain(&rows[dialog]).find("Account actions").unwrap();
    assert_eq!(
        background(dialog, width(&plain(&rows[dialog])[..col])).as_deref(),
        Some("#181b20"),
        "the dialog"
    );
    // Without colour nothing has a colour or a background.
    state.color = false;
    let mono = theme_of(&state);
    assert!(frame(&state, 0).iter().flatten().all(|span| {
        let drawn = props(&mono, &span.style);
        drawn.color.is_none() && drawn.background.is_none()
    }));
}
