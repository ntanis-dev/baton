import { Box, Text } from "ink";
import { branding } from "../art.js";
import { s, wrapLine } from "../lines.js";
import {
  bodyHeight,
  frameCols,
  frameRows,
  sidebarCols,
  tooSmall,
} from "../layout.js";
import { makeTheme, ThemeContext } from "../theme.js";
import { sectionRule } from "../views/common.js";
import { h, Lines } from "./kit.js";
import { Splash } from "./splash.js";

export function LoginScreen({ state, name, url = null, codePrompt = false }) {
  const theme = makeTheme({ color: state.color, glyphs: state.glyphs });
  const cols = frameCols(state),
    rows = frameRows(state);
  const height = bodyHeight(state),
    width = cols - sidebarCols - 6;
  const rail = [
    [],
    ...branding("  "),
    [],
    [],
    [s("  CONNECT ACCOUNT", "muted")],
    [],
    ...wrapLine([s("  " + name, "bold")], sidebarCols - 4, 2),
    [],
    [],
    [s("  01 ", "accent bold"), s("Open your browser", "muted")],
    [],
    [
      s("  02 ", url ? "accent bold" : "muted"),
      s("Sign in to Claude", url ? "text" : "muted"),
    ],
    [],
    [s("  03 ", "muted"), s("Return to Baton", "muted")],
  ];
  const body = [
    [],
    [s("Connect account", "bold")],
    [s("A new connection. The same conversation.", "muted")],
    [],
    [],
    sectionRule("BROWSER SIGN-IN", width, theme.g),
    [],
    ...wrapLine(
      [
        s(
          url ? "Continue in your browser." : "Opening Claude sign-in...",
          "bold",
        ),
      ],
      width,
    ),
    [],
    ...wrapLine(
      [s("Sign in to the Claude account you want to use with Baton.", "muted")],
      width,
    ),
    [],
    [],
    sectionRule("YOUR SIGN-IN LINK", width, theme.g),
    [],
  ];
  const link = url
    ? "\x1b]8;;" +
      url +
      "\x1b\\Open Claude sign-in " +
      theme.g.right +
      "\x1b]8;;\x1b\\"
    : null;
  return h(
    ThemeContext.Provider,
    { value: theme },
    h(
      Box,
      {
        width: cols,
        height: rows,
        flexDirection: "column",
        backgroundColor: theme.tone("background"),
      },
      tooSmall(state)
        ? h(Splash, { state, error: true })
        : h(
            Box,
            { width: cols, height, flexDirection: "row" },
            h(
              Box,
              {
                width: sidebarCols,
                height,
                paddingX: 1,
                flexShrink: 0,
                flexDirection: "column",
                borderStyle: "single",
                borderLeft: false,
                borderTop: false,
                borderBottom: false,
                borderColor: theme.tone("divider"),
                backgroundColor: theme.tone("surface"),
              },
              h(Lines, { lines: rail, width: sidebarCols - 3, height }),
            ),
            h(
              Box,
              {
                width: cols - sidebarCols,
                height,
                paddingX: 3,
                flexDirection: "column",
              },
              h(Lines, { lines: body, width }),
              h(
                Text,
                theme.props("accent bold underline"),
                link ?? "Waiting for your secure link",
              ),
              h(Lines, {
                lines: [
                  [
                    s(
                      url ? new URL(url).hostname : "Generated by Claude Code",
                      "muted",
                    ),
                  ],
                  [],
                  ...wrapLine(
                    [
                      s(
                        url
                          ? "Ctrl+click the link if your browser did not open."
                          : "Your browser will open automatically.",
                        "muted",
                      ),
                    ],
                    width,
                  ),
                ],
                width,
              }),
            ),
            ...(codePrompt
              ? [
                  h(
                    Box,
                    {
                      position: "absolute",
                      marginTop: rows - 6,
                      marginLeft: sidebarCols + 3,
                      flexDirection: "column",
                      width,
                    },
                    h(Lines, {
                      lines: [
                        [s("VERIFICATION CODE", "muted")],
                        [s("Paste your code, then press Enter.", "muted")],
                        [s("> ", "accent bold")],
                      ],
                      width,
                    }),
                  ),
                ]
              : []),
          ),
      ...(!tooSmall(state)
        ? [
            h(Lines, {
              width: cols,
              height: 1,
              lines: [[s("  Ctrl+C", "accent bold"), s(" Cancel", "muted")]],
            }),
          ]
        : []),
    ),
  );
}
